const fs = require('node:fs');
const assert = require('node:assert/strict');
const ts = require('typescript');
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, filename);
const { freshWorld, newPlayer, executeTrade, toPublic, advance, hostAction, equity, newsImpactRemainingSeconds, NEWS_EFFECT_MIN_SECONDS, NEWS_EFFECT_MAX_SECONDS } = require('../src/game/engine.ts');
const { chooseAutonomousNewsPlan } = require('../src/game/autonomous-news.ts');
const now = Date.now();
const { TERMINAL_COUNT, isValidTerminalPath } = require('../src/game/terminals.ts');
const { groupTerminalSessions } = require('../src/game/host-sessions.ts');
assert.equal(TERMINAL_COUNT, 10);
assert.equal(isValidTerminalPath('01'), true);
assert.equal(isValidTerminalPath('10'), true);
assert.equal(isValidTerminalPath('11'), false);
assert.equal(isValidTerminalPath('12'), false);
assert.equal(groupTerminalSessions({ old: { id: 'old', terminalNumber: 11, joinedAt: now, included: true, ended: false } }).length, 0);
const world = freshWorld('test', now);
assert.equal(world.status, 'countdown');
assert.equal(world.duration, 360);
assert.equal(world.remaining, 360);
assert.equal(world.controls.newsSpacing, 75);
assert.equal(world.newsNextAt, world.startedAt + 75_000);
const minimumEffectWorld = freshWorld('live', now);
minimumEffectWorld.status = 'live';
minimumEffectWorld.stocks[0].newsBias = .0011;
const minimumEffect = newsImpactRemainingSeconds(minimumEffectWorld);
const maximumEffectWorld = freshWorld('live', now);
maximumEffectWorld.status = 'live';
maximumEffectWorld.stocks[0].newsBias = .0045;
const maximumEffect = newsImpactRemainingSeconds(maximumEffectWorld);
assert(minimumEffect >= NEWS_EFFECT_MIN_SECONDS && minimumEffect <= NEWS_EFFECT_MAX_SECONDS);
assert(maximumEffect >= NEWS_EFFECT_MIN_SECONDS && maximumEffect <= NEWS_EFFECT_MAX_SECONDS);
const boundedSpacingWorld = freshWorld('live', now);
hostAction(boundedSpacingWorld, 'controls', { newsSpacing: 45 });
assert.equal(boundedSpacingWorld.controls.newsSpacing, 50);
hostAction(boundedSpacingWorld, 'controls', { newsSpacing: 120 });
assert.equal(boundedSpacingWorld.controls.newsSpacing, 90);
const legacyNewsSettingsWorld = freshWorld('live', now);
delete legacyNewsSettingsWorld.newsSettingsVersion;
legacyNewsSettingsWorld.controls.newsSpacing = 65;
advance(legacyNewsSettingsWorld, now);
assert.equal(legacyNewsSettingsWorld.controls.newsSpacing, 75);
assert.equal(legacyNewsSettingsWorld.newsNextAt, now + 75_000);
const quietBrainWorld = freshWorld('live', now);
quietBrainWorld.status = 'live';
quietBrainWorld.stocks.forEach(stock => { stock.price = stock.previousClose; stock.candles = []; });
const quietPlan = chooseAutonomousNewsPlan(quietBrainWorld, now, 75);
assert.equal(quietPlan.setSize, 2);
assert.equal(quietPlan.indices.length, 2);
assert.equal(new Set(quietPlan.indices).size, 2);
assert.equal(quietPlan.intervalSeconds, 55);
const activeBrainWorld = freshWorld('live', now);
activeBrainWorld.status = 'live';
activeBrainWorld.stocks.forEach(stock => { stock.price = stock.previousClose * 1.01; stock.newsBias = .002; });
const activePlan = chooseAutonomousNewsPlan(activeBrainWorld, now, 75);
assert.equal(activePlan.setSize, 2);
assert.equal(activePlan.indices.length, 2);
assert(activePlan.intervalSeconds >= 85 && activePlan.intervalSeconds <= 90);
const autonomousWorld = freshWorld('live', now);
assert.equal(autonomousWorld.autonomousNews.enabled, false);
hostAction(autonomousWorld, 'start', { autonomous: true }, now + 100);
assert.equal(autonomousWorld.autonomousNews.enabled, true);
assert.equal(autonomousWorld.controls.newsEnabled, false);
assert.equal(autonomousWorld.status, 'countdown');
assert([2, 3].includes(autonomousWorld.autonomousNews.nextSetSize));
assert.equal(autonomousWorld.autonomousNews.nextIndices.length, autonomousWorld.autonomousNews.nextSetSize);
assert.equal(autonomousWorld.autonomousNews.nextAt, autonomousWorld.startedAt + 75_000);
assert(autonomousWorld.autonomousNews.history.some(entry => entry.kind === 'planned'));
advance(autonomousWorld, autonomousWorld.startedAt + 90_000);
const firstAutoSet = autonomousWorld.autonomousNews.history.find(entry => entry.kind === 'published').indices;
assert.equal(autonomousWorld.status, 'live');
assert.equal(autonomousWorld.headlines.length, firstAutoSet.length);
assert(autonomousWorld.autonomousNews.history.some(entry => entry.kind === 'published'));
assert(autonomousWorld.autonomousNews.history.some(entry => entry.kind === 'planned'));
assert(autonomousWorld.autonomousNews.nextAt > autonomousWorld.startedAt + 90_000);
assert.equal(toPublic(autonomousWorld, null, 'RELIANCE').autonomousNews, undefined);
const hostSelected = autonomousWorld.news.map((news, index) => ({ news, index })).filter(({ news }) => !autonomousWorld.headlines.some(headline => headline.headline === news.headline)).slice(0, 2).map(item => item.index);
hostAction(autonomousWorld, 'headline', { indices: hostSelected }, autonomousWorld.startedAt + 90_100);
assert(autonomousWorld.autonomousNews.history.some(entry => entry.kind === 'host-published'));
const replacedPlan = [...autonomousWorld.autonomousNews.nextIndices];
hostAction(autonomousWorld, 'autonomous-plan', { indices: replacedPlan }, autonomousWorld.startedAt + 90_200);
assert(autonomousWorld.autonomousNews.history.some(entry => entry.kind === 'host-edited'));
hostAction(autonomousWorld, 'autonomous-skip', {}, autonomousWorld.startedAt + 90_300);
assert(autonomousWorld.autonomousNews.history.some(entry => entry.kind === 'skipped'));
hostAction(autonomousWorld, 'autonomous-publish-now', {}, autonomousWorld.startedAt + 90_400);
assert(autonomousWorld.autonomousNews.history.some(entry => entry.kind === 'host-published'));
hostAction(autonomousWorld, 'autonomous-stop', {}, autonomousWorld.startedAt + 90_500);
assert.equal(autonomousWorld.autonomousNews.enabled, false);
assert(autonomousWorld.autonomousNews.history.some(entry => entry.kind === 'stopped'));
hostAction(autonomousWorld, 'autonomous-start', {}, autonomousWorld.startedAt + 90_600);
assert.equal(autonomousWorld.autonomousNews.enabled, true);
assert.deepEqual(world.stocks.map(s => [s.symbol, s.price]), freshWorld('live', now).stocks.map(s => [s.symbol, s.price]));
const player = newPlayer('engine-smoke-device', world.batch, now, true, 10);
world.sessions[player.id] = player;
assert.throws(() => executeTrade(world, player, 'Buy', 'RELIANCE', 1), /not open yet/);
advance(world, world.startedAt);
assert.equal(world.status, 'live');
executeTrade(world, player, 'Short', 'RELIANCE', 3);
const covered = executeTrade(world, player, 'Buy', 'RELIANCE', 3);
assert.equal(player.shorts.RELIANCE, undefined);
assert.match(covered.note, /Covered 3/);
executeTrade(world, player, 'Buy', 'TCS', 4);
executeTrade(world, player, 'Sell', 'TCS', 4);
assert.equal(player.holdings.TCS, undefined);
assert.throws(() => executeTrade(world, player, 'Buy', 'RELIANCE', 100_000), /Not enough cash/);
const snapshot = toPublic(world, player.id, 'TCS');
assert.equal(snapshot.stocks.length, 28);
assert.equal(snapshot.stocks.filter(stock => stock.candles.length).length, 1);
assert(snapshot.stocks.every(stock => stock.trend.length === 18));
assert.equal(snapshot.participants, 1);
assert.deepEqual(snapshot.terminalSummaries.map(({ terminalNumber, status }) => [terminalNumber, status]), [[10, 'live']]);
assert.equal(snapshot.terminalSummaries[0].cash, player.cash);
assert.equal(snapshot.terminalSummaries[0].totalValue, equity(world, player));
assert.equal(snapshot.terminalSummaries[0].pnl, snapshot.terminalSummaries[0].totalValue - player.initialCash);
const compact = Buffer.byteLength(JSON.stringify(snapshot));
const full = Buffer.byteLength(JSON.stringify(world));
advance(world, world.lastTickAt + 80_000);
assert(world.tick > 0 && world.headlines.length > 0);
assert.equal(world.remaining, 280);
assert.equal(world.newsNextAt, world.startedAt + 150_000);
executeTrade(world, player, 'Short', 'TCS', 2);
advance(world, world.startedAt + world.duration * 1000 + 1);
assert.equal(world.status, 'closed');
assert.equal(world.remaining, 0);
assert.equal(player.ended, true);
assert.deepEqual(player.shorts, {});
const nextBatchAt = world.startedAt + world.duration * 1000 + 2;
// Simulate the participant polling the finished batch just before the next starts.
player.lastSeenAt = nextBatchAt - 1;
const nextBatch = hostAction(world, 'start', {}, nextBatchAt);
assert.equal(nextBatch.batch, 2);
assert.equal(nextBatch.status, 'countdown');
assert.equal(nextBatch.remaining, nextBatch.duration);
assert.equal(nextBatch.tick, 0);
assert.equal(nextBatch.sessions[player.id].ended, false);
const fullChart = toPublic(world, player.id, 'TCS');
const chartSince = fullChart.stocks.find(stock => stock.symbol === 'TCS').candles.at(-3).time;
const deltaChart = toPublic(world, player.id, 'TCS', { candlesSince: chartSince });
assert(deltaChart.stocks.find(stock => stock.symbol === 'TCS').candles.length < fullChart.stocks.find(stock => stock.symbol === 'TCS').candles.length);
assert.equal(toPublic(world, player.id, 'TCS', { includeCandles: false }).stocks.find(stock => stock.symbol === 'TCS').candles.length, 0);
console.log(`PASS: 10-terminal bounds, audience summaries, 15% longer news effects, adaptive autonomous news (2–3 headlines), host start/stop/skip/edit/early-publish controls, public snapshot privacy, 75-second default, countdown, trading, cash guard, close/settlement/restart and chart deltas; snapshot ${compact} bytes vs ${full} bytes (${Math.round((1-compact/full)*100)}% smaller)`);
