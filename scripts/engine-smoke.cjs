const fs = require('node:fs');
const assert = require('node:assert/strict');
const ts = require('typescript');
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, filename);
const { freshWorld, newPlayer, executeTrade, toPublic, advance, hostAction } = require('../src/game/engine.ts');
const now = Date.now();
const world = freshWorld('test', now);
assert.equal(world.status, 'countdown');
assert.equal(world.duration, 360);
assert.equal(world.remaining, 360);
assert.deepEqual(world.stocks.map(s => [s.symbol, s.price]), freshWorld('live', now).stocks.map(s => [s.symbol, s.price]));
const player = newPlayer('engine-smoke-device', world.batch);
world.sessions[player.id] = player;
assert.throws(() => executeTrade(world, player, 'Buy', 'RELIANCE', 1), /not open yet/);
advance(world, world.startedAt);
assert.equal(world.status, 'live');
executeTrade(world, player, 'Short', 'RELIANCE', 3);
const covered = executeTrade(world, player, 'Buy', 'RELIANCE', 3);
assert.equal(player.shorts.RELIANCE, undefined);
assert.match(covered.note, /Covered 3/);
executeTrade(world, player, 'Buy', 'TCS', 4);
executeTrade(world, player, 'Sell', 'TCS', 4);
assert.equal(player.holdings.TCS, undefined);
assert.throws(() => executeTrade(world, player, 'Buy', 'RELIANCE', 100_000), /Not enough cash/);
const snapshot = toPublic(world, player.id, 'TCS');
assert.equal(snapshot.stocks.length, 28);
assert.equal(snapshot.stocks.filter(stock => stock.candles.length).length, 1);
assert(snapshot.stocks.every(stock => stock.trend.length === 18));
const compact = Buffer.byteLength(JSON.stringify(snapshot));
const full = Buffer.byteLength(JSON.stringify(world));
advance(world, world.lastTickAt + 80_000);
assert(world.tick > 0 && world.headlines.length > 0);
assert.equal(world.remaining, 280);
executeTrade(world, player, 'Short', 'TCS', 2);
advance(world, world.startedAt + world.duration * 1000 + 1);
assert.equal(world.status, 'closed');
assert.equal(world.remaining, 0);
assert.equal(player.ended, true);
assert.deepEqual(player.shorts, {});
const nextBatch = hostAction(world, 'start', {}, world.startedAt + world.duration * 1000 + 2);
assert.equal(nextBatch.batch, 2);
assert.equal(nextBatch.status, 'countdown');
assert.equal(nextBatch.remaining, nextBatch.duration);
assert.equal(nextBatch.tick, 0);
assert.equal(nextBatch.sessions[player.id].ended, false);
const fullChart = toPublic(world, player.id, 'TCS');
const chartSince = fullChart.stocks.find(stock => stock.symbol === 'TCS').candles.at(-3).time;
const deltaChart = toPublic(world, player.id, 'TCS', { candlesSince: chartSince });
assert(deltaChart.stocks.find(stock => stock.symbol === 'TCS').candles.length < fullChart.stocks.find(stock => stock.symbol === 'TCS').candles.length);
assert.equal(toPublic(world, player.id, 'TCS', { includeCandles: false }).stocks.find(stock => stock.symbol === 'TCS').candles.length, 0);
console.log(`PASS: countdown, matching initial prices, buy/sell/short/cover, cash guard, six-minute close/settlement/restart, chart deltas; snapshot ${compact} bytes vs ${full} bytes (${Math.round((1-compact/full)*100)}% smaller)`);
